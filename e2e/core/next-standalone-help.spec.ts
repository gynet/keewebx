import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { activateVaultUtility } from './vault-utilities';
import * as kdbx from '../../modules/db/lib';
import { argon2 } from '../../modules/db/test/test-support/argon2';

for (const width of [1280, 320]) test.describe(`standalone help ${width}`, () => {
    test.use({ viewport: { width, height: 740 } });
    test('license and dependency notices are readable offline; browser tabs have no standalone reload', async ({ page, context }) => {
        await page.goto('/next.html');
        await activateVaultUtility(page, 'Settings');
        await expect(page.getByRole('button', { name: 'Reload app', exact: true })).toHaveCount(0);
        await context.setOffline(true);
        await page.getByText('Help and about KeeWebX', { exact: true }).click();
        await page.getByText('License text', { exact: true }).click();
        expect(await page.getByLabel('License text', { exact: true }).textContent()).toBe(readFileSync('LICENSE', 'utf8'));
        await page.getByText('Credits and dependency notices', { exact: true }).click();
        expect(await page.getByLabel('Credits and dependency notices', { exact: true }).textContent()).toBe(readFileSync('THIRD-PARTY-LICENSES.md', 'utf8'));
        await expect(page.getByLabel('Credits and dependency notices', { exact: true })).toContainText('| 0.1.3 | Apache-2.0 | ui-classic, ui |');
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
        await page.screenshot({ path: test.info().outputPath('credits.png'), fullPage: true });
    });
    test('standalone reload waits for saved and locked vaults, supports cancellation and performs a real reload', async ({ page }) => {
        await page.addInitScript(() => Object.defineProperty(navigator, 'standalone', { configurable: true, value: true }));
        kdbx.CryptoEngine.setArgon2Impl(argon2);
        const password = 'Standalone fixture master';
        const db = kdbx.Kdbx.create(new kdbx.Credentials(kdbx.ProtectedValue.fromString(password)), 'Standalone fixture');
        db.header.kdfParameters!.set('M', kdbx.VarDictionary.ValueType.UInt64, kdbx.Int64.from(32 * 1024));
        db.header.kdfParameters!.set('I', kdbx.VarDictionary.ValueType.UInt64, kdbx.Int64.from(2));
        const entry = db.createEntry(db.getDefaultGroup()); entry.fields.set('Title', 'Saved account');
        entry.fields.set('Password', kdbx.ProtectedValue.fromString('Preserved secret'));
        await page.goto('/next.html');
        await page.locator('#open-file-input').setInputFiles({ name: 'standalone.kdbx', mimeType: 'application/octet-stream', buffer: Buffer.from(await db.save()) });
        await page.locator('#password').fill(password); await page.locator('#unlock').click();
        await page.locator('.entry-row').filter({ hasText: 'Saved account' }).click();
        await page.getByRole('button', { name: 'Edit', exact: true }).click();
        await page.locator('.entry-editor textarea').fill('Draft survives reload refusal');
        await activateVaultUtility(page, 'Settings');
        const reload = page.getByRole('button', { name: 'Reload app', exact: true });
        await expect(reload).toBeDisabled();
        await page.getByRole('button', { name: 'Back to vault', exact: true }).filter({ visible: true }).click();
        await expect(page.locator('.entry-editor textarea')).toHaveValue('Draft survives reload refusal');
        await page.locator('.entry-editor').getByRole('button', { name: 'Save', exact: true }).click();
        await activateVaultUtility(page, 'Settings');
        await expect(reload).toBeDisabled();
        await page.getByRole('tab', { name: 'Database', exact: true }).click();
        const downloaded = page.waitForEvent('download'); await page.getByRole('button', { name: 'Download KDBX', exact: true }).click();
        const stream = await (await downloaded).createReadStream(); if (!stream) throw new Error('No encrypted download');
        const chunks: Buffer[] = []; for await (const chunk of stream) chunks.push(Buffer.from(chunk));
        const reopened = await kdbx.Kdbx.load(new Uint8Array(Buffer.concat(chunks)).buffer, new kdbx.Credentials(kdbx.ProtectedValue.fromString(password)));
        const saved = [...reopened.getDefaultGroup().allEntries()][0];
        expect(saved.fields.get('Notes')).toBe('Draft survives reload refusal');
        expect(saved.fields.get('Password')).toBeInstanceOf(kdbx.ProtectedValue);
        expect((saved.fields.get('Password') as kdbx.ProtectedValue).getText()).toBe('Preserved secret');
        await page.getByRole('button', { name: 'Back to vault', exact: true }).filter({ visible: true }).click();
        await activateVaultUtility(page, 'Lock'); await expect(page.locator('#password')).toBeVisible();
        await activateVaultUtility(page, 'Settings'); await expect(reload).toBeEnabled();
        page.once('dialog', dialog => dialog.dismiss()); await reload.click();
        await expect(reload).toBeEnabled();
        page.once('dialog', dialog => dialog.accept());
        await Promise.all([page.waitForEvent('framenavigated', frame => frame === page.mainFrame()), reload.click()]);
        await expect(page.locator('#password')).toBeVisible();
        await page.locator('#password').fill(password); await page.locator('#unlock').click();
        await page.locator('.entry-row').filter({ hasText: 'Saved account' }).click();
        await expect(page.locator('.detail')).toContainText('Draft survives reload refusal');
    });
});
