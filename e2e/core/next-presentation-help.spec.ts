import { test, expect } from '@playwright/test';

for (const width of [1280, 320]) test(`extension guidance and diagnostics are usable at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 });
    await page.goto('/next.html'); await page.locator('#open-demo').click();
    await expect(page.locator('.entry-row').first()).toBeVisible();
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    await page.getByRole('tab', { name: 'Browser extension', exact: true }).click();
    await page.getByText('Install and connect KeeWebX Connect', { exact: true }).click();
    const setup = page.getByRole('region', { name: 'Browser extension setup', exact: true });
    await expect(setup.getByRole('link', { name: 'Extension downloads', exact: true })).toHaveAttribute('href', 'https://github.com/gynet/keewebx/releases');
    await setup.getByRole('combobox').selectOption('firefox');
    await expect(setup).toContainText('about:debugging');
    await setup.getByRole('combobox').selectOption('edge');
    await expect(setup).toContainText('edge://extensions');
    await setup.getByRole('combobox').selectOption('other');
    await expect(setup).toContainText('Safari and native password-manager integration are not provided');
    const locked = setup.getByLabel('Ask to unlock when an extension requests a login', { exact: true });
    const empty = setup.getByLabel('Show the entry chooser when no website matches', { exact: true });
    await expect(locked).toBeChecked(); await expect(empty).toBeChecked();
    await locked.uncheck(); await empty.uncheck();
    await page.getByRole('tab', { name: 'Appearance', exact: true }).click();
    await page.getByText('Troubleshooting and issue reports', { exact: true }).click();
    const diagnostics = page.getByRole('region', { name: 'Help and diagnostics', exact: true });
    const text = await diagnostics.getByLabel('Diagnostics', { exact: true }).innerText();
    expect(text).toContain('Environment: web'); expect(text).toContain('Browser:');
    expect(text).not.toMatch(/s3cret|Demo\.kdbx|github.com\/login/);
    const issue = new URL((await diagnostics.getByRole('link', { name: 'Open an issue draft', exact: true }).getAttribute('href'))!);
    expect(issue.origin).toBe('https://github.com'); expect(issue.searchParams.get('body')).toContain(text);
    await diagnostics.getByText('Application logs', { exact: true }).click();
    await diagnostics.getByRole('button', { name: 'Refresh logs', exact: true }).click();
    await expect(diagnostics.getByRole('status')).toContainText(/\d+ recent events/);
    await expect(diagnostics.locator('ol')).toContainText('Key derivation finished');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: test.info().outputPath(`help-${width}.png`), fullPage: true });
    await page.reload();
    await page.locator('#open-demo').click();
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    await page.getByRole('tab', { name: 'Browser extension', exact: true }).click();
    await expect(locked).not.toBeChecked(); await expect(empty).not.toBeChecked();
});
