import { activateVaultUtility } from './vault-utilities';
import { test, expect } from '@playwright/test';

for (const width of [1280, 320]) test(`extension guidance and diagnostics are usable at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 });
    await page.goto('/next.html'); await page.locator('#open-demo').click();
    await expect(page.locator('.entry-row').first()).toBeVisible();
    await activateVaultUtility(page, 'Settings');
    await page.getByRole('tab', { name: 'Browser extension', exact: true }).click();
    await page.getByText('Install and connect KeeWebX Connect', { exact: true }).click();
    const setup = page.getByRole('region', { name: 'Browser extension setup', exact: true });
    await expect(setup.getByRole('link', { name: 'Extension downloads', exact: true })).toHaveAttribute('href', 'https://github.com/gynet/keewebx/releases');
    await setup.getByRole('combobox').selectOption('firefox');
    await expect(setup).toContainText('about:debugging');
    await setup.getByRole('combobox').selectOption('edge');
    await expect(setup).toContainText('edge://extensions');
    await setup.getByRole('combobox').selectOption('other');
    await expect(setup).toContainText('Use a supported Chrome, Chromium, Edge, or Firefox desktop browser. For iOS Safari, see the Userscripts setup below.');
    await setup.getByText('iOS Safari with Userscripts (experimental)', { exact: true }).click();
    await expect(setup.getByRole('link', { name: 'Download Connect userscript', exact: true }))
        .toHaveAttribute('href', 'https://raw.githubusercontent.com/gynet/keewebx/userscript-v0.5.0/modules/extension/userscript/keewebx-connect.user.js');
    await expect(setup.getByRole('link', { name: 'Userscripts setup guide', exact: true }))
        .toHaveAttribute('href', 'https://github.com/gynet/keewebx/tree/master/modules/extension/userscript#readme');
    await expect(setup).toContainText('select Allow for account listing once. All login websites then use this tab.');
    await expect(setup).toContainText('Subsequent fills reuse the connection; no further authorization is needed.');
    const locked = setup.getByLabel('Ask to unlock when an extension requests a login', { exact: true });
    const empty = setup.getByLabel('Show the entry chooser when no website matches', { exact: true });
    await expect(locked).toBeChecked(); await expect(empty).toBeChecked();
    await locked.uncheck(); await empty.uncheck();
    await page.getByRole('tab', { name: 'Appearance', exact: true }).click();
    await page.getByText('Troubleshooting and issue reports', { exact: true }).click();
    const diagnostics = page.getByRole('region', { name: 'Help and diagnostics', exact: true });
    const text = await diagnostics.getByLabel('Diagnostics', { exact: true }).innerText();
    expect(text).toContain('Environment: web'); expect(text).toContain('Browser:');
    expect(text).toMatch(/^KeeWebX \d+\.\d+\.\d+/); expect(text).toMatch(/Build: \d{4}-\d{2}-\d{2}/);
    expect(text).toMatch(/Commit: (?:unavailable|[a-f0-9]{7,40})/); expect(text).not.toContain('@@');
    await diagnostics.getByText('Web app updates', { exact: true }).click();
    await expect(diagnostics).toContainText('lock your vaults and use Reload to update');
    await diagnostics.getByText('Keyboard reference', { exact: true }).click();
    await expect(diagnostics.locator('.shortcut-reference dt')).toHaveCount(27);
    await expect(diagnostics.locator('.shortcut-reference')).toContainText('Apply valid drafts and save vaults');
    await expect(diagnostics.locator('.shortcut-reference')).toContainText('Open workspace, including editors');
    await expect(diagnostics.locator('.shortcut-reference')).toContainText(/(?:Ctrl|Command) \+ S/);
    await page.getByText('Help and about KeeWebX', { exact: true }).click();
    await expect(page.getByRole('link', { name: 'Release history', exact: true })).toHaveAttribute('href', 'https://github.com/gynet/keewebx/releases');
    await expect(page.getByRole('link', { name: 'Source code', exact: true })).toHaveAttribute('href', 'https://github.com/gynet/keewebx');
    expect(text).not.toMatch(/s3cret|Demo\.kdbx|github.com\/login/);
    const issue = new URL((await diagnostics.getByRole('link', { name: 'Open an issue draft', exact: true }).getAttribute('href'))!);
    expect(issue.origin).toBe('https://github.com'); expect(issue.searchParams.get('body')).toContain(text);
    await diagnostics.getByText('Application logs', { exact: true }).click();
    await diagnostics.getByRole('button', { name: 'Refresh logs', exact: true }).click();
    await expect(diagnostics.getByRole('status')).toContainText(/\d+ recent events/);
    await expect(diagnostics.locator('ol')).toContainText('Key derivation finished');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: test.info().outputPath(`help-${width}.png`), fullPage: true });
    await page.reload();
    await page.locator('#open-demo').click(); await expect(page.locator('.entry-row').first()).toBeVisible();
    await activateVaultUtility(page, 'Settings');
    await page.getByRole('tab', { name: 'Browser extension', exact: true }).click();
    await expect(locked).not.toBeChecked(); await expect(empty).not.toBeChecked();
});
