import { activateVaultUtility } from './vault-utilities';
import { test, expect } from '@playwright/test';
import * as kdbx from '../../modules/db/lib';
import { argon2 } from '../../modules/db/test/test-support/argon2';

const password = 'Language fixture password';
const title = 'Settings $& {} <script> untouched';
for (const width of [1280, 320]) test.describe(`language ${width}`, () => {
    test.use({ locale: 'de-DE', viewport: { width, height: 900 } });
    test('browser language and persisted choice update controls without replacing data or drafts', async ({ page }) => {
        kdbx.CryptoEngine.setArgon2Impl(argon2);
        const db = kdbx.Kdbx.create(new kdbx.Credentials(kdbx.ProtectedValue.fromString(password)), 'Untranslated vault');
        db.header.kdfParameters!.set('M', kdbx.VarDictionary.ValueType.UInt64, kdbx.Int64.from(32 * 1024));
        db.header.kdfParameters!.set('I', kdbx.VarDictionary.ValueType.UInt64, kdbx.Int64.from(2));
        const original = db.createEntry(db.getDefaultGroup());
        original.fields.set('Title', title); original.fields.set('UserName', 'Username');
        original.fields.set('Password', kdbx.ProtectedValue.fromString('NotTranslatedSecret'));
        original.fields.set('CustomName', kdbx.ProtectedValue.fromString('$& {} <b>protected</b>'));
        await page.goto('/next.html');
        await expect(page.locator('html')).toHaveAttribute('lang', 'de-DE');
        await expect(page.getByRole('button', { name: 'Demo ausprobieren', exact: true })).toBeVisible();
        await page.locator('#open-file-input').setInputFiles({ name: 'language.kdbx', mimeType: 'application/octet-stream', buffer: Buffer.from(await db.save()) });
        await page.locator('#password').fill(password); await page.locator('#unlock').click();
        await page.locator('.entry-row').filter({ hasText: title }).click();
        await expect(page.locator('#entry-title')).toHaveText(title);
        await page.getByRole('button', { name: 'Bearbeiten', exact: true }).click();
        const notes = page.locator('.entry-editor textarea');
        await notes.fill('Draft $& {} <script> remains literal');
        await activateVaultUtility(page, 'Einstellungen', { browseName: 'Tresor durchsuchen' });
        await expect(page.getByText('Classic ist veraltet und bleibt aus Kompatibilitätsgründen verfügbar.', { exact: true })).toBeVisible();
        await expect(page.locator('#use-classic')).toHaveAccessibleName('Classic');
        await page.locator('#setting-locale').selectOption('fr-FR');
        await expect(page.getByRole('heading', { name: 'Paramètres', exact: true })).toBeVisible();
        await expect(page.locator('html')).toHaveAttribute('lang', 'fr-FR');
        await expect(page.getByText('Classic est obsolète et reste disponible pour des raisons de compatibilité.', { exact: true })).toBeVisible();
        await expect(page.locator('#use-classic')).toHaveAccessibleName('Classic');
        await page.screenshot({ path: test.info().outputPath(`language-fr-${width}.png`) });
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
        await page.getByRole('button', { name: 'Retour au coffre', exact: true }).filter({ visible: true }).click();
        await expect(notes).toHaveValue('Draft $& {} <script> remains literal');
        await page.locator('.entry-editor').getByRole('button', { name: 'Enregistrer', exact: true }).click();
        await expect(page.locator('#entry-title')).toHaveText(title);
        await activateVaultUtility(page, 'Paramètres', { browseName: 'Parcourir le coffre' });
        await page.getByRole('tab', { name: 'Base de données', exact: true }).click();
        const pending = page.waitForEvent('download'); await page.getByRole('button', { name: 'Télécharger le KDBX', exact: true }).click();
        const stream = await (await pending).createReadStream(); if (!stream) throw new Error('Missing encrypted file');
        const chunks: Buffer[] = []; for await (const chunk of stream) chunks.push(Buffer.from(chunk));
        const bytes = Buffer.concat(chunks); expect(bytes.includes(Buffer.from('NotTranslatedSecret'))).toBe(false);
        const reopened = await kdbx.Kdbx.load(new Uint8Array(bytes).buffer, new kdbx.Credentials(kdbx.ProtectedValue.fromString(password)));
        const entries = [...reopened.getDefaultGroup().allEntries()]; expect(entries).toHaveLength(1);
        expect(entries[0].uuid.id).toBe(original.uuid.id); expect(entries[0].fields.get('Title')).toBe(title);
        expect(entries[0].fields.get('UserName')).toBe('Username'); expect(entries[0].fields.get('Notes')).toBe('Draft $& {} <script> remains literal');
        expect(entries[0].fields.get('Password')).toBeInstanceOf(kdbx.ProtectedValue);
        expect((entries[0].fields.get('CustomName') as kdbx.ProtectedValue).getText()).toBe('$& {} <b>protected</b>');
        await page.getByRole('button', { name: 'Retour au coffre', exact: true }).filter({ visible: true }).click();
        await activateVaultUtility(page, 'Verrouiller', { browseName: 'Parcourir le coffre' });
        await expect(page.locator('#password')).toBeVisible(); await page.reload();
        await expect(page.locator('html')).toHaveAttribute('lang', 'fr-FR');
        await page.locator('#password').fill(password); await page.locator('#unlock').click();
        await expect(page.locator('.entry-row')).toHaveCount(1);
        await activateVaultUtility(page, 'Paramètres', { browseName: 'Parcourir le coffre' });
        await expect(page.locator('#setting-locale')).toHaveValue('fr-FR');
        await page.locator('#setting-locale').selectOption('en-US');
        await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible();
        await page.locator('#setting-locale').selectOption('');
        await expect(page.getByRole('heading', { name: 'Einstellungen', exact: true })).toBeVisible();
        await expect(page.locator('html')).toHaveAttribute('lang', 'de-DE');
    });
});
