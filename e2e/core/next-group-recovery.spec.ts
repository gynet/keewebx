import { test, expect } from '@playwright/test';
import * as kdbx from '../../modules/db/lib';
import { argon2 } from '../../modules/db/test/test-support/argon2';

test('group modal retains an invalid raw create draft through recovery; locking a delete modal never confirms deletion', async ({ page }, testInfo) => {
    test.setTimeout(90_000);
    await page.clock.install();
    kdbx.CryptoEngine.setArgon2Impl(argon2);
    const password = 'disposable group recovery';
    const db = kdbx.Kdbx.create(new kdbx.Credentials(kdbx.ProtectedValue.fromString(password)), 'Modal fixture');
    const group = db.createGroup(db.groups[0], 'Guarded group');
    const entry = db.createEntry(group);
    entry.fields.set('Title', 'Retained modal record');
    entry.fields.set('Password', kdbx.ProtectedValue.fromString('Retained modal secret'));
    await page.goto('/next.html');
    await page.locator('#open-file-input').setInputFiles({ name: 'modal-vault.kdbx', mimeType: 'application/octet-stream', buffer: Buffer.from(await db.save()) });
    await page.locator('#password').fill(password);
    await page.locator('#unlock').click();
    await expect(page.locator('#sync-state')).toHaveText('Up to date', { timeout: 30_000 });
    await page.locator('#open-settings').click();
    await page.locator('#setting-auto-lock').selectOption('5');
    await page.locator('#settings-back').click();
    const navigation = page.getByRole('navigation', { name: 'Vault', exact: true });
    await navigation.getByRole('button', { name: 'Guarded group', exact: true }).click();
    await navigation.getByRole('button', { name: 'Manage groups', exact: true }).click();
    const actions = page.getByRole('group', { name: 'Group actions: Guarded group', exact: true });
    await actions.getByRole('button', { name: 'New group', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'New group', exact: true });
    await dialog.getByLabel('Group name', { exact: true }).fill('   ');
    await page.clock.fastForward(6 * 60_000);
    const retained = page.locator('dialog[aria-label="New group"]');
    await expect(retained).toHaveCount(1);
    await expect(retained).toBeHidden();
    await expect(retained).toHaveJSProperty('open', false);
    await expect(retained.locator('xpath=ancestor::*[@inert and @hidden]')).toHaveCount(1);
    await expect(retained.getByLabel('Group name', { exact: true })).toHaveValue('   ');
    await expect(dialog).toHaveCount(0);
    const recovery = page.getByRole('form', { name: 'Verify database: modal-vault', exact: true });
    await expect(recovery).toBeVisible({ timeout: 30_000 });
    await recovery.getByLabel('Master password', { exact: true }).fill('wrong modal password');
    await recovery.getByLabel('Master password', { exact: true }).press('Enter');
    await expect(recovery.getByRole('alert')).toContainText('Verification failed');
    await expect(recovery.getByLabel('Master password', { exact: true })).toBeFocused();
    await expect(retained).toBeHidden();
    await recovery.getByLabel('Master password', { exact: true }).fill(password);
    await recovery.getByLabel('Master password', { exact: true }).press('Enter');
    await expect(recovery.getByRole('status')).toHaveText('Verified');
    await expect(page.getByRole('button', { name: 'Return to unsaved changes', exact: true })).toBeFocused();
    await page.keyboard.press('Enter');
    await expect(dialog).toBeVisible();
    await expect(dialog).toHaveJSProperty('open', true);
    expect(await dialog.evaluate(element => element.matches(':modal'))).toBe(true);
    await expect(dialog.getByLabel('Group name', { exact: true })).toHaveValue('   ');
    await expect(dialog.getByLabel('Group name', { exact: true })).toBeFocused();
    await page.screenshot({ path: testInfo.outputPath('restored-group-modal.png'), fullPage: true });
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    await expect(navigation.getByRole('button', { name: 'Guarded group', exact: true })).toBeVisible();
    await actions.getByRole('button', { name: 'Delete group', exact: true }).click();
    await expect(page.getByRole('dialog', { name: 'Move group to trash', exact: true })).toBeVisible();
    await page.clock.fastForward(6 * 60_000);
    await expect(page.locator('#password')).toBeVisible({ timeout: 30_000 });
    await page.locator('#password').fill(password);
    await page.locator('#unlock').click();
    await expect(navigation.getByRole('button', { name: 'Guarded group', exact: true })).toBeVisible({ timeout: 30_000 });
    await expect(page.locator('.entry-row').filter({ hasText: 'Retained modal record' })).toBeVisible();
    await page.locator('#open-settings').click();
    const pending = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download KDBX', exact: true }).click();
    const download = await pending;
    expect(await download.failure()).toBeNull();
    const stream = await download.createReadStream();
    if (!stream) throw new Error('No encrypted output');
    const chunks: Buffer[] = [];
    for await (const chunk of stream) chunks.push(Buffer.from(chunk));
    const reopened = await kdbx.Kdbx.load(new Uint8Array(Buffer.concat(chunks)).buffer, new kdbx.Credentials(kdbx.ProtectedValue.fromString(password)));
    const surviving = reopened.getGroup(group.uuid);
    expect(surviving?.name).toBe('Guarded group');
    expect(surviving?.groups).toHaveLength(0);
    const ids = (roots: kdbx.KdbxGroup[]): string[] => roots.flatMap(group => [group.uuid.id, ...ids(group.groups)]);
    expect(ids(reopened.groups).sort()).toEqual(ids(db.groups).sort());
    expect(surviving?.parentGroup?.uuid.id).toBe(db.groups[0].uuid.id);
    expect(surviving?.entries[0].uuid.id).toBe(entry.uuid.id);
    expect((surviving?.entries[0].fields.get('Password') as kdbx.ProtectedValue).getText()).toBe('Retained modal secret');
});
