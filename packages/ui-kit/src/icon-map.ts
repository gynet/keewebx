export function entryIconName(name?: string | null) {
    return name && Object.prototype.hasOwnProperty.call(ENTRY_ICON_MAP, name)
        ? ENTRY_ICON_MAP[name as keyof typeof ENTRY_ICON_MAP]
        : ENTRY_ICON_MAP.key;
}

